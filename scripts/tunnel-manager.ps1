#Requires -Version 5.1
<#
.SYNOPSIS
    Tunnel Manager - Auto-recovery for Cloudflare quick tunnels.
.DESCRIPTION
    Checks if tunnel URLs are alive. If dead, restarts cloudflared tunnels
    and writes new URLs to TUNNEL-URLS-latest.md.
    
    Usage:
        tunnel-manager.ps1 -Check          # Just check status
        tunnel-manager.ps1 -Restart        # Force restart all tunnels
        tunnel-manager.ps1 -Auto           # Check and restart if needed (for watchdog)
        tunnel-manager.ps1 -Start          # Start tunnels if not running
#>

param(
    [switch]$Check,
    [switch]$Restart,
    [switch]$Auto,
    [switch]$Start
)

$ErrorActionPreference = "Continue"

# Config
$CF = "C:\tmp\cloudflared.exe"
$LOG_DIR = "C:\tmp"
$URLS_DOC = "C:\Users\souro\.vibe\docs\TUNNEL-URLS-latest.md"
$STATUS_FILE = "C:\Users\souro\.mcp-autostart\tunnel-status.json"
$LOCK_FILE = "C:\Users\souro\.mcp-autostart\tunnel-manager.lock"

$PORTS = @(
    @{ Port = 3000; Name = "connector";     McpPath = "/mcp" },
    @{ Port = 3001; Name = "browser";       McpPath = "/mcp" },
    @{ Port = 3002; Name = "gateway";       McpPath = "/mcp" },
    @{ Port = 3939; Name = "latch";         McpPath = "/mcp/mistral" }
)

# Prevent concurrent runs
if (Test-Path $LOCK_FILE) {
    $lockAge = (Get-Date) - (Get-Item $LOCK_FILE).LastWriteTime
    if ($lockAge.TotalMinutes -lt 10) {
        Write-Host "Lock file exists (age: $($lockAge.TotalSeconds)s). Another instance may be running. Exiting."
        exit 0
    }
    Remove-Item $LOCK_FILE -Force
}
New-Item -ItemType File -Path $LOCK_FILE -Force | Out-Null

trap {
    if (Test-Path $LOCK_FILE) { Remove-Item $LOCK_FILE -Force -ErrorAction SilentlyContinue }
    exit 1
}

function Get-TunnelUrl {
    param([int]$Port)
    $logFile = "$LOG_DIR\tunnel-$Port.log"
    if (-not (Test-Path $logFile)) { return $null }
    $content = Get-Content $logFile -Raw -ErrorAction SilentlyContinue
    if ($content -match 'https://[a-z0-9-]+\.trycloudflare\.com') {
        return $Matches[0]
    }
    return $null
}

function Test-TunnelAlive {
    param([string]$Url, [string]$McpPath)
    if (-not $Url) { return $false }
    try {
        $healthUrl = "$Url/health"
        $response = Invoke-WebRequest -Uri $healthUrl -Method GET -TimeoutSec 5 -UseBasicParsing -ErrorAction Stop
        return ($response.StatusCode -eq 200)
    } catch {
        try {
            $mcpUrl = "$Url$McpPath"
            $body = '{"jsonrpc":"2.0","id":1,"method":"tools/list"}'
            $response = Invoke-WebRequest -Uri $mcpUrl -Method POST -Body $body -ContentType "application/json" -TimeoutSec 5 -UseBasicParsing -ErrorAction Stop
            return ($response.StatusCode -eq 200)
        } catch {
            return $false
        }
    }
}

function Test-LocalService {
    param([int]$Port)
    try {
        $conn = Get-NetTCPConnection -LocalPort $Port -ErrorAction Stop | Select-Object -First 1
        return ($null -ne $conn)
    } catch {
        return $false
    }
}

function Stop-AllTunnels {
    Write-Host "Stopping all cloudflared processes..."
    Get-Process cloudflared -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 2
}

function Start-Tunnel {
    param([hashtable]$Svc)
    
    $port = $Svc.Port
    $name = $Svc.Name
    $logFile = "$LOG_DIR\tunnel-$port.log"
    
    Remove-Item $logFile -Force -ErrorAction SilentlyContinue
    
    $argList = @("tunnel", "--url", "http://localhost:$port", "--no-autoupdate", "--logfile", $logFile, "--loglevel", "info")
    $proc = Start-Process -FilePath $CF -ArgumentList $argList -WindowStyle Hidden -PassThru
    
    Write-Host "  Started $name tunnel for port $port (PID $($proc.Id))"
    return $proc.Id
}

function Wait-ForTunnelUrl {
    param([int]$Port, [int]$TimeoutSec = 30)
    
    $logFile = "$LOG_DIR\tunnel-$Port.log"
    $elapsed = 0
    
    while ($elapsed -lt $TimeoutSec) {
        Start-Sleep -Seconds 2
        $elapsed += 2
        
        if (Test-Path $logFile) {
            $content = Get-Content $logFile -Raw -ErrorAction SilentlyContinue
            if ($content -match 'https://[a-z0-9-]+\.trycloudflare\.com') {
                return $Matches[0]
            }
            if ($content -match 'status 429') {
                Write-Host "  RATE LIMITED (429) for port $Port. Need to wait longer."
                return $null
            }
        }
    }
    return $null
}

function Write-UrlsDoc {
    param([array]$TunnelInfo)
    
    $lines = @()
    $lines += "# Cloudflare Tunnel URLs (auto-generated $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))"
    $lines += ""
    $lines += "Generated by tunnel-manager.ps1"
    $lines += ""
    $lines += "| Service | Port | Tunnel URL | MCP Endpoint | Status |"
    $lines += "|---------|------|-----------|-------------|--------|"
    
    foreach ($t in $TunnelInfo) {
        $mcpEndpoint = "$($t.Url)$($t.McpPath)"
        $lines += "| $($t.Name) | $($t.Port) | $($t.Url) | $mcpEndpoint | $($t.Status) |"
    }
    
    $lines += ""
    $lines += "## Gotchas"
    $lines += ""
    $lines += "- Tunnel URLs are **ephemeral** — they change every time cloudflared restarts."
    $lines += "- After restart, update Mistral AI connectors with the new URLs."
    $lines += "- Use `--logfile` flag (NOT PowerShell `RedirectStandardError`)."
    $lines += "- Cloudflare rate-limits quick tunnel creation (HTTP 429). Wait 5+ minutes between restart attempts."
    $lines += "- DNS propagation may take ~30s after tunnel registration."
    $lines += ""
    $lines += "## Auto-Recovery"
    $lines += ""
    $lines += "Run ``tunnel-manager.ps1 -Auto`` to check and restart if needed."
    $lines += "Schedule via Task Scheduler every 5 minutes for automatic recovery."
    
    $lines | Out-File -FilePath $URLS_DOC -Encoding UTF8 -Force
    Write-Host "URLs written to $URLS_DOC"
}

function Write-StatusJson {
    param([array]$TunnelInfo)
    
    $status = @{
        lastCheck = (Get-Date -Format "o")
        tunnels = @()
    }
    
    foreach ($t in $TunnelInfo) {
        $status.tunnels += @{
            name = $t.Name
            port = $t.Port
            url = $t.Url
            localUp = $t.LocalUp
            tunnelUp = $t.TunnelUp
            status = $t.Status
        }
    }
    
    $status | ConvertTo-Json -Depth 5 | Out-File -FilePath $STATUS_FILE -Encoding UTF8 -Force
}

# Determine mode
$mode = if ($Check) { "check" } elseif ($Restart) { "restart" } elseif ($Start) { "start" } else { "auto" }

Write-Host "=== Tunnel Manager ($mode) ==="
Write-Host "Time: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"

$tunnelInfo = @()
$needRestart = $false

foreach ($svc in $PORTS) {
    $port = $svc.Port
    $name = $svc.Name
    $mcpPath = $svc.McpPath
    
    $localUp = Test-LocalService -Port $port
    $url = Get-TunnelUrl -Port $port
    $tunnelUp = $false
    
    if ($url) {
        $tunnelUp = Test-TunnelAlive -Url $url -McpPath $mcpPath
    }
    
    $status = if (-not $localUp) { "LOCAL_DOWN" } elseif (-not $url) { "NO_URL" } elseif (-not $tunnelUp) { "TUNNEL_DOWN" } else { "OK" }
    
    Write-Host "  $name (port $port): local=$localUp, url=$(if($url){'yes'}else{'no'}), tunnel=$tunnelUp => $status"
    
    $tunnelInfo += @{
        Name = $name
        Port = $port
        Url = $url
        McpPath = $mcpPath
        LocalUp = $localUp
        TunnelUp = $tunnelUp
        Status = $status
    }
    
    if ($status -ne "OK") { $needRestart = $true }
}

Write-Host ""

switch ($mode) {
    "check" {
        Write-StatusJson -TunnelInfo $tunnelInfo
        if ($needRestart) { exit 1 } else { exit 0 }
    }
    
    "start" {
        if (-not $needRestart) {
            Write-Host "All tunnels OK. Nothing to do."
            Write-StatusJson -TunnelInfo $tunnelInfo
            exit 0
        }
        foreach ($t in $tunnelInfo) {
            if ($t.Status -ne "OK" -and $t.LocalUp) {
                $svc = $PORTS | Where-Object { $_.Port -eq $t.Port } | Select-Object -First 1
                Start-Tunnel -Svc $svc
                Start-Sleep -Seconds 15
            }
        }
        Start-Sleep -Seconds 10
        $newInfo = @()
        foreach ($svc in $PORTS) {
            $url = Wait-ForTunnelUrl -Port $svc.Port -TimeoutSec 30
            $newInfo += @{
                Name = $svc.Name; Port = $svc.Port; Url = $url; McpPath = $svc.McpPath
                LocalUp = $true; TunnelUp = ($null -ne $url)
                Status = $(if ($url) { "OK" } else { "FAILED" })
            }
        }
        Write-UrlsDoc -TunnelInfo $newInfo
        Write-StatusJson -TunnelInfo $newInfo
    }
    
    "restart" {
        Stop-AllTunnels
        Start-Sleep -Seconds 3
        
        foreach ($svc in $PORTS) {
            Start-Tunnel -Svc $svc
            Start-Sleep -Seconds 15
        }
        
        Start-Sleep -Seconds 10
        $newInfo = @()
        foreach ($svc in $PORTS) {
            $url = Wait-ForTunnelUrl -Port $svc.Port -TimeoutSec 30
            $newInfo += @{
                Name = $svc.Name; Port = $svc.Port; Url = $url; McpPath = $svc.McpPath
                LocalUp = $true; TunnelUp = ($null -ne $url)
                Status = $(if ($url) { "OK" } else { "FAILED" })
            }
        }
        Write-UrlsDoc -TunnelInfo $newInfo
        Write-StatusJson -TunnelInfo $newInfo
    }
    
    "auto" {
        if (-not $needRestart) {
            Write-Host "All tunnels OK. Nothing to do."
            Write-StatusJson -TunnelInfo $tunnelInfo
            exit 0
        }
        
        Write-Host "Some tunnels are down. Attempting auto-recovery..."
        
        $localDown = $tunnelInfo | Where-Object { -not $_.LocalUp }
        if ($localDown) {
            Write-Host "WARNING: Local services down: $($localDown.Name -join ', ')"
            Write-Host "Start local services first, then run tunnel-manager again."
        }
        
        $toRestart = $tunnelInfo | Where-Object { $_.LocalUp -and $_.Status -ne "OK" }
        if ($toRestart) {
            Stop-AllTunnels
            Start-Sleep -Seconds 3
            
            foreach ($t in $toRestart) {
                $svc = $PORTS | Where-Object { $_.Port -eq $t.Port } | Select-Object -First 1
                Start-Tunnel -Svc $svc
                Start-Sleep -Seconds 15
            }
            
            Start-Sleep -Seconds 10
            $newInfo = @()
            foreach ($svc in $PORTS) {
                $url = Wait-ForTunnelUrl -Port $svc.Port -TimeoutSec 30
                $localUp = Test-LocalService -Port $svc.Port
                $tunnelUp = $false
                if ($url) { $tunnelUp = Test-TunnelAlive -Url $url -McpPath $svc.McpPath }
                
                $status = if (-not $localUp) { "LOCAL_DOWN" } elseif (-not $url) { "NO_URL" } elseif (-not $tunnelUp) { "TUNNEL_DOWN" } else { "OK" }
                
                $newInfo += @{
                    Name = $svc.Name; Port = $svc.Port; Url = $url; McpPath = $svc.McpPath
                    LocalUp = $localUp; TunnelUp = $tunnelUp; Status = $status
                }
                Write-Host "  $($svc.Name): $status $(if($url){$url}else{''})"
            }
            Write-UrlsDoc -TunnelInfo $newInfo
            Write-StatusJson -TunnelInfo $newInfo
            
            $failed = $newInfo | Where-Object { $_.Status -ne "OK" }
            if ($failed) {
                Write-Host "WARNING: Some tunnels failed: $($failed.Name -join ', ')"
                Write-Host "May be Cloudflare rate limiting (429). Wait 5+ minutes and retry."
                exit 1
            }
        }
    }
}

if (Test-Path $LOCK_FILE) { Remove-Item $LOCK_FILE -Force -ErrorAction SilentlyContinue }
Write-Host "=== Done ==="
